  internal class Glyph(
    val data: String,
    val stroke: Boolean = false,
    val roundCap: Boolean = false,
    val roundJoin: Boolean = false,
    val alpha: Float = 1f,
    val width: Float = 1.5f,
    val evenOdd: Boolean = false,
  )

  internal fun icon(name: String, vararg glyphs: Glyph, viewport: Float = 24f): ImageVector =
    ImageVector.Builder(
      name = name,
      defaultWidth = 24.dp,
      defaultHeight = 24.dp,
      viewportWidth = viewport,
      viewportHeight = viewport,
    ).apply {
      glyphs.forEach { glyph ->
        val nodes = PathParser().parsePathString(glyph.data).toNodes()
        if (glyph.stroke) {
          addPath(
            pathData = nodes,
            stroke = SolidColor(Color.Black),
            strokeAlpha = glyph.alpha,
            strokeLineWidth = glyph.width,
            strokeLineCap = if (glyph.roundCap) StrokeCap.Round else StrokeCap.Butt,
            strokeLineJoin = if (glyph.roundJoin) StrokeJoin.Round else StrokeJoin.Miter,
          )
        } else {
          addPath(
            pathData = nodes,
            fill = SolidColor(Color.Black),
            fillAlpha = glyph.alpha,
            pathFillType = if (glyph.evenOdd) PathFillType.EvenOdd else PathFillType.NonZero,
          )
        }
      }
    }.build()
